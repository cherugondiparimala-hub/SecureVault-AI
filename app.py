from PIL import Image
from pytesseract import Output


def redact_pdf(input_path, output_path):
    pdf = fitz.open(input_path)

    if pdf.is_encrypted:
        pdf.close()
        raise ValueError("Please upload an unlocked PDF.")

    total_detected = 0
    total_redacted = 0
    warnings = []

    try:
        for page_number, page in enumerate(pdf, start=1):
            page_text = page.get_text("text")
            rectangles_to_redact = []

            if page_text.strip():
                # Searchable PDF: use its actual text positions.
                findings = detect_sensitive_information(page_text)
                total_detected += len(findings)

                for item in findings:
                    rects = page.search_for(item["value"])

                    if rects:
                        rectangles_to_redact.extend(rects)
                    else:
                        warnings.append(
                            f"Page {page_number}: Could not locate "
                            f"one detected {item['type']}."
                        )

            else:
                # Scanned/image PDF: render page and run OCR.
                pix = page.get_pixmap(
                    matrix=fitz.Matrix(3, 3),
                    alpha=False
                )

                image = Image.frombytes(
                    "RGB",
                    [pix.width, pix.height],
                    pix.samples
                )

                ocr = pytesseract.image_to_data(
                    image,
                    output_type=Output.DICT,
                    config="--psm 6"
                )

                # Group OCR words by text line.
                lines = {}

                for i, word in enumerate(ocr["text"]):
                    word = word.strip()

                    if not word:
                        continue

                    key = (
                        ocr["block_num"][i],
                        ocr["par_num"][i],
                        ocr["line_num"][i]
                    )

                    lines.setdefault(key, []).append({
                        "text": word,
                        "left": ocr["left"][i],
                        "top": ocr["top"][i],
                        "width": ocr["width"][i],
                        "height": ocr["height"][i]
                    })

                scale = 3.0

                for words in lines.values():
                    line_text = " ".join(
                        word["text"] for word in words
                    )

                    findings = detect_sensitive_information(line_text)
                    total_detected += len(findings)

                    # Map each match back to its OCR word boxes.
                    spans = []
                    position = 0

                    for word in words:
                        start = position
                        end = start + len(word["text"])
                        spans.append((start, end, word))
                        position = end + 1

                    for item in findings:
                        matching_words = [
                            word
                            for start, end, word in spans
                            if start < item["end"]
                            and end > item["start"]
                        ]

                        if not matching_words:
                            continue

                        left = min(
                            w["left"] for w in matching_words
                        )
                        top = min(
                            w["top"] for w in matching_words
                        )
                        right = max(
                            w["left"] + w["width"]
                            for w in matching_words
                        )
                        bottom = max(
                            w["top"] + w["height"]
                            for w in matching_words
                        )

                        # Convert rendered-image coordinates to PDF points.
                        rect = fitz.Rect(
                            left / scale,
                            top / scale,
                            right / scale,
                            bottom / scale
                        )

                        rectangles_to_redact.append(rect)

            # Apply genuine PDF redactions.
            if rectangles_to_redact:
                for rect in rectangles_to_redact:
                    page.add_redact_annot(
                        rect,
                        fill=(0, 0, 0)
                    )

                page.apply_redactions()
                total_redacted += len(rectangles_to_redact)

            if not page_text.strip():
                warnings.append(
                    f"Page {page_number} was processed with OCR. "
                    "OCR may misread characters; verify the output."
                )

        pdf.save(
            output_path,
            garbage=4,
            deflate=True
        )

    finally:
        pdf.close()

    return total_detected, total_redacted, warnings

def process_document(file_path):
    if not file_path:
        return "Please upload a TXT or PDF file.", "", None

    extension = os.path.splitext(file_path)[1].lower()

    if extension not in [".txt", ".pdf"]:
        return "Please upload a TXT or PDF file.", "", None

    output_fd, output_path = tempfile.mkstemp(
        suffix="_masked.pdf"
    )
    os.close(output_fd)

    try:
        # Process TXT files
        if extension == ".txt":
            with open(
                file_path,
                "r",
                encoding="utf-8-sig",
                errors="replace"
            ) as file:
                original_text = file.read()

            findings = detect_sensitive_information(original_text)
            masked_text = mask_text(original_text, findings)

            create_pdf_from_text(masked_text, output_path)

            categories = sorted(
                set(item["type"] for item in findings)
            )
            category_text = (
                ", ".join(categories)
                if categories else "None detected"
            )

            report = (
                "## Analysis Complete\n\n"
                "**File type:** TXT\n\n"
                f"**Sensitive items detected:** {len(findings)}\n\n"
                "**Output:** Masked PDF generated\n\n"
                f"**Detected categories:** {category_text}"
            )

            return report, masked_text, output_path

        # Process PDF files
        with fitz.open(file_path) as source_pdf:
            if source_pdf.is_encrypted:
                raise ValueError(
                    "Please upload an unlocked PDF."
                )

            original_text = "\n".join(
                page.get_text("text")
                for page in source_pdf
            )

        findings = detect_sensitive_information(original_text)
        masked_preview = mask_text(original_text, findings)

        detected, redacted, warnings = redact_pdf(
            file_path,
            output_path
        )

        categories = sorted(
            set(item["type"] for item in findings)
        )
        category_text = (
            ", ".join(categories)
            if categories else "None detected"
        )

        report = (
            "## Analysis Complete\n\n"
            "**File type:** PDF\n\n"
            f"**Sensitive items detected:** {detected}\n\n"
            f"**Text locations redacted:** {redacted}\n\n"
            f"**Detected categories:** {category_text}\n\n"
            "**Output:** Redacted PDF generated"
        )

        if warnings:
            report += "\n\n### Warnings\n"
            report += "\n".join(
                f"- {warning}" for warning in warnings
            )

        if not original_text.strip():
            report += (
                "\n\n**Note:** No searchable text was found. "
                "Scanned PDFs require OCR for detection."
            )

        return report, masked_preview, output_path

    except Exception as error:
        if os.path.exists(output_path):
            os.remove(output_path)

        return (
            f"**Processing failed:** {error}",
            "",
            None
        )

