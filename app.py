PATTERNS = [
    (
        "Aadhaar-like number",
        re.compile(
            r"(?<!\d)(?:\d{4}[ -]?){2}\d{4}(?!\d)"
        )
    ),
    (
        "PAN-like number",
        re.compile(
            r"(?<![A-Z0-9])[A-Z]{5}\d{4}[A-Z]"
            r"(?![A-Z0-9])",
            re.IGNORECASE
        )
    ),
    (
        "Email address",
        re.compile(
            r"(?i)(?<![\w.+-])"
            r"[A-Z0-9._%+-]+@[A-Z0-9.-]+\.[A-Z]{2,}"
        )
    ),
    (
        "Indian mobile number",
        re.compile(
            r"(?<!\d)(?:\+91[\s-]?)?[6-9]\d{9}(?!\d)"
        )
    )
]


def detect_sensitive_information(text):
    findings = []

    for label, pattern in PATTERNS:
        for match in pattern.finditer(text):
            findings.append({
                "type": label,
                "value": match.group(),
                "start": match.start(),
                "end": match.end()
            })

    # Prefer longer, more specific matches when patterns overlap.
    findings.sort(
        key=lambda item: (
            item["start"],
            -(item["end"] - item["start"])
        )
    )

    filtered = []

    for item in findings:
        overlaps = any(
            item["start"] < previous["end"]
            and item["end"] > previous["start"]
            for previous in filtered
        )

        if not overlaps:
            filtered.append(item)

    return sorted(filtered, key=lambda item: item["start"])


def mask_text(text, findings):
    result = text

    for item in reversed(findings):
        result = (
            result[:item["start"]]
            + "[REDACTED]"
            + result[item["end"]:]
        )

    return result

def create_pdf_from_text(text, output_path):
    document = SimpleDocTemplate(
        output_path,
        pagesize=A4,
        rightMargin=0.7 * inch,
        leftMargin=0.7 * inch,
        topMargin=0.7 * inch,
        bottomMargin=0.7 * inch
    )

    styles = getSampleStyleSheet()
    story = [
        Paragraph(
            "SecureVault AI - Masked Document",
            styles["Title"]
        ),
        Spacer(1, 20)
    ]

    for line in text.splitlines():
        if line.strip():
            safe_line = escape(line)
            story.append(
                Paragraph(safe_line, styles["BodyText"])
            )
            story.append(Spacer(1, 5))
        else:
            story.append(Spacer(1, 8))

    document.build(story)

